/// Methods that panic on the unexpected case.
const PANICKING_METHODS: &[&str] = &["unwrap", "expect", "unwrap_err", "expect_err"];

/// Text inside an inert macro's arguments that makes it assert after all.
const PANICKING_TOKENS: &[&str] = &[
    "unwrap",
    "expect",
    "assert",
    "panic",
    "unreachable",
    "todo",
    "unimplemented",
    "?",
];

pub(super) fn check(source: &str) -> Vec<Finding> {
    let Some(file) = parse_file(source) else {
        return Vec::new();
    };
    let mut items = Items::default();
    items.visit_file(&file);
    let context = Context {
        functions: &items.functions,
        bound_checks: &items.bound_checks,
    };
    items
        .tests
        .iter()
        .filter(|f| !context.asserts_block(&f.block, HELPER_DEPTH) && !compiles_only(f, &context))
        .map(|f| {
            let name = f.sig.ident.to_string();
            let line = f.sig.ident.span().start().line;
            let subject = format!("The test `{name}` (line {line})");
            Finding {
                line,
                name,
                message: message(&subject, f.block.stmts.is_empty()),
            }
        })
        .collect()
}

/// Every test function, and every function by name.
#[derive(Default)]
struct Items<'ast> {
    tests: Vec<&'ast syn::ItemFn>,
    functions: HashMap<String, Vec<&'ast syn::Block>>,
    /// Generic functions with an empty body: compile-time bound checks when called.
    bound_checks: HashSet<String>,
}

impl<'ast> Visit<'ast> for Items<'ast> {
    fn visit_item_fn(&mut self, f: &'ast syn::ItemFn) {
        if f.block.stmts.is_empty() && !f.sig.generics.params.is_empty() {
            self.bound_checks.insert(f.sig.ident.to_string());
        }
        self.functions
            .entry(f.sig.ident.to_string())
            .or_default()
            .push(&f.block);
        if is_running_test(&f.attrs) {
            self.tests.push(f);
        }
        syn::visit::visit_item_fn(self, f);
    }

    fn visit_impl_item_fn(&mut self, f: &'ast syn::ImplItemFn) {
        self.functions
            .entry(f.sig.ident.to_string())
            .or_default()
            .push(&f.block);
        syn::visit::visit_impl_item_fn(self, f);
    }
}

/// `#[test]` or `#[x::test]`, not marked to be skipped or to expect a panic, and not generated
/// from case attributes.
fn is_running_test(attrs: &[syn::Attribute]) -> bool {
    let last = |a: &syn::Attribute| {
        a.path()
            .segments
            .last()
            .map(|s| s.ident.to_string())
            .unwrap_or_default()
    };
    attrs.iter().any(|a| last(a) == "test")
        && !attrs.iter().any(|a| {
            matches!(
                last(a).as_str(),
                "should_panic" | "ignore" | "test_case" | "rstest" | "case"
            )
        })
}

struct Context<'a, 'ast> {
    functions: &'a HashMap<String, Vec<&'ast syn::Block>>,
    bound_checks: &'a HashSet<String>,
}

impl Context<'_, '_> {
    fn asserts_block(&self, block: &syn::Block, depth: usize) -> bool {
        let mut finder = Finder {
            context: self,
            depth,
            found: false,
        };
        finder.visit_block(block);
        finder.found
    }

    /// A call of a path: a name that checks, a same-file helper that asserts, or a free function
    /// defined somewhere the checker cannot see (another file of the crate, another crate), which
    /// may be a helper that asserts. Without import resolution, only calls that cannot be helpers
    /// are read as not asserting: a constructor (`Some(x)`, `Ok(())`), an associated function of
    /// a type (`Router::new()`), a function of the standard library, and `drop`.
    fn path_call_asserts(&self, path: &syn::Path, depth: usize) -> bool {
        let segments: Vec<String> = path.segments.iter().map(|s| s.ident.to_string()).collect();
        let Some(last) = segments.last() else {
            return false;
        };
        if names_an_assertion(last) {
            return true;
        }
        // A function of this file (reached as `helper`, `super::helper` or `Self::helper`).
        if let Some(blocks) = self.functions.get(last) {
            return depth > 0 && blocks.iter().any(|b| self.asserts_block(b, depth - 1));
        }
        let starts_upper = |s: &str| s.starts_with(|c: char| c.is_ascii_uppercase());
        match segments.as_slice() {
            [only] => !(starts_upper(only) || only == "drop"),
            [.., owner, _] => {
                let std = matches!(segments[0].as_str(), "std" | "core" | "alloc");
                !(std || starts_upper(owner) || PRIMITIVES.contains(&owner.as_str()))
            }
            [] => false,
        }
    }

    /// A method call: a method of this file that asserts, or a method the file does not define
    /// and the standard library does not explain, which may be a helper of a type from another
    /// file or crate (`trybuild`'s `t.pass(..)`, a harness's `run()`).
    fn method_call_asserts(&self, method: &str, depth: usize) -> bool {
        if let Some(blocks) = self.functions.get(method) {
            return depth > 0 && blocks.iter().any(|b| self.asserts_block(b, depth - 1));
        }
        !STD_METHODS.contains(&method)
    }

    /// A function of this file with generic parameters and an empty body: called with a turbofish
    /// and no arguments it is a compile-time bound check (`is_send::<Order>()`).
    fn is_bound_check(&self, call: &syn::ExprCall) -> bool {
        let syn::Expr::Path(p) = call.func.as_ref() else {
            return false;
        };
        let Some(last) = p.path.segments.last() else {
            return false;
        };
        call.args.is_empty()
            && matches!(last.arguments, syn::PathArguments::AngleBracketed(_))
            && self.bound_checks.contains(&last.ident.to_string())
    }
}

/// A test whose only job is to compile: it holds a coercion check (`let _: fn(u32) -> u32 =
/// total;`, `let _: &dyn Render = &widget;`) or a bound-checking call, and no runtime assertion.
/// It fails when the code stops compiling, which is its check.
fn compiles_only(test: &syn::ItemFn, context: &Context<'_, '_>) -> bool {
    struct Seen<'c, 'a, 'ast> {
        context: &'c Context<'a, 'ast>,
        found: bool,
    }
    impl<'v> Visit<'v> for Seen<'_, '_, '_> {
        fn visit_local(&mut self, local: &'v syn::Local) {
            if let syn::Pat::Type(typed) = &local.pat {
                if names_a_coercion_target(&typed.ty) {
                    self.found = true;
                }
            }
            syn::visit::visit_local(self, local);
        }

        fn visit_expr_call(&mut self, e: &'v syn::ExprCall) {
            if self.context.is_bound_check(e) {
                self.found = true;
            }
            syn::visit::visit_expr_call(self, e);
        }
    }
    let mut seen = Seen {
        context,
        found: false,
    };
    seen.visit_block(&test.block);
    seen.found
}

/// A function-pointer, trait-object or `impl Trait` type: annotating a binding with one checks
/// at compile time that the value fits it.
fn names_a_coercion_target(ty: &syn::Type) -> bool {
    match ty {
        syn::Type::BareFn(_) | syn::Type::TraitObject(_) | syn::Type::ImplTrait(_) => true,
        syn::Type::Reference(r) => names_a_coercion_target(&r.elem),
        syn::Type::Paren(p) => names_a_coercion_target(&p.elem),
        syn::Type::Group(g) => names_a_coercion_target(&g.elem),
        _ => false,
    }
}

struct Finder<'c, 'a, 'ast> {
    context: &'c Context<'a, 'ast>,
    depth: usize,
    found: bool,
}

impl<'v> Visit<'v> for Finder<'_, '_, '_> {
    fn visit_macro(&mut self, mac: &'v syn::Macro) {
        let name = mac
            .path
            .segments
            .last()
            .map(|s| s.ident.to_string())
            .unwrap_or_default();
        if !INERT_MACROS.contains(&name.as_str()) {
            self.found = true;
            return;
        }
        let tokens = mac.tokens.to_string();
        if PANICKING_TOKENS.iter().any(|t| tokens.contains(t)) {
            self.found = true;
        }
    }

    fn visit_expr_try(&mut self, e: &'v syn::ExprTry) {
        self.found = true;
        syn::visit::visit_expr_try(self, e);
    }

    fn visit_expr_method_call(&mut self, e: &'v syn::ExprMethodCall) {
        let method = e.method.to_string();
        if PANICKING_METHODS.contains(&method.as_str())
            || names_an_assertion(&method)
            || self.context.method_call_asserts(&method, self.depth)
        {
            self.found = true;
        }
        syn::visit::visit_expr_method_call(self, e);
    }

    fn visit_expr_call(&mut self, e: &'v syn::ExprCall) {
        if let syn::Expr::Path(p) = e.func.as_ref() {
            if self.context.path_call_asserts(&p.path, self.depth) {
                self.found = true;
            }
        }
        syn::visit::visit_expr_call(self, e);
    }
}
