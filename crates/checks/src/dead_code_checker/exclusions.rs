//! Candidate exclusions: files that are never reported as dead because a tool, a person or a
//! test runner loads them by name rather than by import. Pure predicates over a path or the
//! head of a file; no I/O.
//!
//! These are guards `G1` (tests, fixtures, mocks, stories, e2e), `G2` (declaration files),
//! `G3` (root-level, dot-dir and config-shaped files), `G11` (generated markers) and `G12`
//! (the `keep-file:` marker) of the design spec.

use crate::extract::paths::is_test_path;

/// How many leading lines the generated and keep markers are read from.
const MARKER_LINES: usize = 10;

fn basename(path: &str) -> &str {
    path.rsplit('/').next().unwrap_or(path)
}

/// Test, fixture, mock, story and end-to-end files. The shared [`is_test_path`] plus the
/// conventions the dead-code rule additionally meets: pytest's `conftest.py`, `test_*.py` and
/// `tests.py`, NestJS-style `*.e2e-spec.ts`, and snapshot files. Test code is live by
/// definition; the test file is a root, so a helper imported only by tests stays live.
pub(super) fn is_test_file(path: &str) -> bool {
    if is_test_path(path) {
        return true;
    }
    let lower = path.to_ascii_lowercase();
    if lower.split('/').any(|s| s == "__snapshots__") || lower.ends_with(".snap") {
        return true;
    }
    let file = basename(&lower);
    if matches!(file, "conftest.py" | "tests.py") {
        return true;
    }
    if file.starts_with("test_") && file.ends_with(".py") {
        return true;
    }
    file.rfind('.').is_some_and(|dot| {
        let stem = &file[..dot];
        stem.ends_with(".e2e") || stem.ends_with(".e2e-spec")
    })
}

/// `*.d.ts`, `*.d.mts`, `*.d.cts` and `*.pyi`: consumed by the type checker through
/// `include`, `typeRoots` or triple-slash references, never imported.
pub(super) fn is_declaration_file(path: &str) -> bool {
    let lower = path.to_ascii_lowercase();
    [".d.ts", ".d.mts", ".d.cts", ".pyi"]
        .iter()
        .any(|suffix| lower.ends_with(suffix))
}

/// Basenames (lowercase) that tools load by name, matched as `<name>.<anything>`.
const CONFIG_BASENAME_PREFIXES: &[&str] = &[
    "setuptests.",
    "test-setup.",
    "instrumentation.",
    "middleware.",
    "proxy.",
    "service-worker.",
    "sw.",
    "manifest.",
    "reportwebvitals.",
    "polyfills.",
    "preload.",
    "env.",
    "global.",
    "globals.",
    "register.",
    "vite-env.",
    "next-env.",
];

/// Whether a path is root-level, inside or named like a dot-directory, or shaped like a file a
/// tool loads by name (`*.config.*`, `*rc.js`, `*.setup.*`, `middleware.*` and the like).
pub(super) fn is_config_shaped(path: &str) -> bool {
    if !path.contains('/') {
        return true;
    }
    if path.split('/').any(|seg| seg.starts_with('.')) {
        return true;
    }
    let file = basename(path).to_ascii_lowercase();
    if file.contains(".config.")
        || file.contains(".conf.")
        || file.contains(".setup.")
        || file.contains(".workspace.")
    {
        return true;
    }
    if ["rc.js", "rc.cjs", "rc.mjs", "rc.ts"]
        .iter()
        .any(|suffix| file.ends_with(suffix))
    {
        return true;
    }
    CONFIG_BASENAME_PREFIXES
        .iter()
        .any(|prefix| file.starts_with(prefix))
}

/// Generated code by NAME: a `.gen.` or `.generated.` file, or anything in a `generated/` or
/// `__generated__/` folder. The scan prunes these from the audited list but hands them over as
/// reference text, because a router or codegen step is often the only importer of hand-written
/// files (TanStack's `routeTree.gen.ts` imports every route). Codegen output is regenerated, not
/// deleted, so it is never reported, and what it imports is alive.
pub(super) fn is_generated_path(path: &str) -> bool {
    let lower = path.to_ascii_lowercase();
    let mut segments: Vec<&str> = lower.split('/').collect();
    let file = segments.pop().unwrap_or("");
    segments
        .iter()
        .any(|s| matches!(*s, "generated" | "__generated__"))
        || file.contains(".gen.")
        || file.contains(".generated.")
}

/// Markers (lowercase) that a tool wrote the file and a person should not edit it.
const GENERATED_MARKERS: &[&str] = &[
    "@generated",
    "code generated",
    "do not edit",
    "auto-generated",
    "automatically generated",
    "autogenerated",
];

fn head_lines(content: &str) -> impl Iterator<Item = &str> {
    content.lines().take(MARKER_LINES)
}

/// A generated-file marker in the first ten lines. Codegen output is regenerated, not deleted.
pub(super) fn has_generated_marker(content: &str) -> bool {
    head_lines(content).any(|line| {
        let lower = line.to_ascii_lowercase();
        GENERATED_MARKERS.iter().any(|m| lower.contains(m))
    })
}

/// The `keep-file:` marker followed by a reason, in the first ten lines. The reason is what
/// travels with the code, so a marker with nothing after the colon does not count.
pub(super) fn has_keep_marker(content: &str) -> bool {
    head_lines(content).any(|line| {
        line.find("keep-file:")
            .is_some_and(|i| !line[i + "keep-file:".len()..].trim().is_empty())
    })
}
