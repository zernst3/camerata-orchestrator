//! File-level guards D1 to D7: each skipped path or content has a reason, and each is proved
//! with the same body that IS indexed when it sits in an ordinary path.

use super::*;

fn reason_of(path: &str, content: &str) -> Option<SkipReason> {
    let input = files(&[(path, content)]);
    index_of(&input)
        .skipped
        .into_iter()
        .find(|(p, _)| p == path)
        .map(|(_, reason)| reason)
}

#[test]
fn the_control_body_is_indexed_in_an_ordinary_path() {
    let src = ts_discount_default("0.2");
    assert_eq!(reason_of("src/cart.ts", &src), None);
}

